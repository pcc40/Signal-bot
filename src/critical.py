"""Critical CSS: the first-screen rules inlined in <head>, so the first paint does not wait for the full stylesheet
(Netlify reported First Contentful Paint "needs improvement", November 2026).

src/critical.json is generated by tools/make_critical.js: per stylesheet (site.css, site-rtl.css) the md5 of the sheet
and one cut per page group. A cut is used only while that hash matches the current stylesheet; otherwise the page
falls back to the ordinary render-blocking <link>, so an edit to site.css without re-running the tool costs speed,
never styling. build.py (English pages) and tools/i18n.py (translated pages, and the right-to-left swap on /ar/)
both call css_tags()."""
import hashlib, json
from pathlib import Path

SRC = Path(__file__).resolve().parent
ASSETS = SRC / "static" / "assets"
GROUPS = ("insights", "work", "services", "areas", "tools", "guides")   # keep in step with tools/make_critical.js
_DATA = None

def sheet_hash(sheet):
    return hashlib.md5((ASSETS / sheet).read_bytes()).hexdigest()[:8]

def group_of(path):
    """Page group of an English or translated path: home, one of GROUPS, or other."""
    parts = [p for p in path.split("/") if p]
    if parts and parts[0] in ("ar", "ru", "zh", "hi"):
        parts = parts[1:]
    if not parts:
        return "home"
    return parts[0] if parts[0] in GROUPS else "other"

def critical_css(sheet, path):
    """The inlinable first-screen CSS for `sheet` on `path`, or None when missing or out of date."""
    global _DATA
    if _DATA is None:
        try:
            _DATA = json.loads((SRC / "critical.json").read_text(encoding="utf-8"))
        except (OSError, ValueError):
            _DATA = {}
    d = _DATA.get(sheet) or {}
    if d.get("hash") != sheet_hash(sheet):
        return None
    css = (d.get("groups") or {}).get(group_of(path))
    return css if css and "</" not in css else None

def css_tags(path, sheet="site.css"):
    """<head> markup for the stylesheet: critical CSS inline and the full sheet loaded without blocking the first
    paint (preload, switched to a stylesheet on load; <noscript> fallback), or a plain <link> when the critical
    cut is stale or missing. The ?v= query is the stylesheet's own hash, so a changed file is never served from cache."""
    href = f"/assets/{sheet}?v={sheet_hash(sheet)}"
    crit = critical_css(sheet, path)
    if not crit:
        return f'<link rel="stylesheet" href="{href}">'
    return (f'<style id="critical-css">{crit}</style>\n'
            f'<link rel="preload" href="{href}" as="style" onload="this.onload=null;this.rel=\'stylesheet\'">\n'
            f'<noscript><link rel="stylesheet" href="{href}"></noscript>')
